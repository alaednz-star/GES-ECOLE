-- ------------------------------------------------------------------ guard
CREATE OR REPLACE FUNCTION public.guard_formation_type()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
DECLARE
  _base text;
  _code text;
  _n    int := 1;
BEGIN
  -- Migrations, the service role and SECURITY DEFINER code pass through.
  IF current_user <> 'authenticated' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  IF TG_OP = 'INSERT' THEN
    NEW.built_in := false;
    -- The code is the type's permanent identity: generated here, never chosen by a client.
    _base := regexp_replace(
               translate(lower(btrim(NEW.name)),
                         'àâäáãåçéèêëíìîïñóòôöõúùûüýÿ', 'aaaaaaceeeeiiiinooooouuuuyy'),
               '[^a-z0-9]+', '_', 'g');
    _base := btrim(_base, '_');
    IF _base = '' THEN
      _base := substr(md5(gen_random_uuid()::text), 1, 8);   -- e.g. an Arabic-only name
    END IF;
    _base := 'custom_' || left(_base, 40);
    _code := _base;
    WHILE EXISTS (SELECT 1 FROM public.formation_types WHERE code = _code) LOOP
      _n := _n + 1;
      _code := _base || '_' || _n;
    END LOOP;
    NEW.code := _code;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF OLD.built_in THEN
      RAISE EXCEPTION 'A built-in formation type cannot be deleted; deactivate it instead.'
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
  END IF;

  -- UPDATE
  IF NEW.code IS DISTINCT FROM OLD.code OR NEW.built_in IS DISTINCT FROM OLD.built_in THEN
    RAISE EXCEPTION 'The code and built-in flag of a formation type cannot be changed.'
      USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.built_in AND (NEW.name IS DISTINCT FROM OLD.name
                       OR NEW.description IS DISTINCT FROM OLD.description) THEN
    RAISE EXCEPTION 'A built-in formation type keeps its translated name and description.'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.guard_formation_type() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS t_formation_types_guard ON public.formation_types;
CREATE TRIGGER t_formation_types_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.formation_types
  FOR EACH ROW EXECUTE FUNCTION public.guard_formation_type();

DROP TRIGGER IF EXISTS t_formation_types_updated ON public.formation_types;
CREATE TRIGGER t_formation_types_updated
  BEFORE UPDATE ON public.formation_types
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ------------------------------------------------------------------ RLS
ALTER TABLE public.formation_types ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.formation_types FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.formation_types TO authenticated;
GRANT ALL ON public.formation_types TO service_role;

DROP POLICY IF EXISTS "formation types read" ON public.formation_types;
CREATE POLICY "formation types read" ON public.formation_types
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "formation types admin write" ON public.formation_types;
CREATE POLICY "formation types admin write" ON public.formation_types
  FOR ALL TO authenticated
  USING (private.is_admin()) WITH CHECK (private.is_admin());

-- ------------------------------------------------------------------ programs.category -> code
ALTER TABLE public.programs DROP CONSTRAINT IF EXISTS programs_category_check;
ALTER TABLE public.programs DROP CONSTRAINT IF EXISTS programs_category_fkey;
ALTER TABLE public.programs
  ADD CONSTRAINT programs_category_fkey FOREIGN KEY (category)
  REFERENCES public.formation_types (code) ON UPDATE RESTRICT ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_programs_category ON public.programs (category);

-- An inactive type stays on the formations that already use it, but is not given to a new one.
CREATE OR REPLACE FUNCTION public.enforce_formation_type_active()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.category IS NOT DISTINCT FROM OLD.category THEN
    RETURN NEW;
  END IF;
  IF EXISTS (SELECT 1 FROM public.formation_types
              WHERE code = NEW.category AND status <> 'active') THEN
    RAISE EXCEPTION 'The formation type "%" is inactive: it cannot be given to a formation.', NEW.category
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.enforce_formation_type_active() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS t_programs_type_active ON public.programs;
CREATE TRIGGER t_programs_type_active
  BEFORE INSERT OR UPDATE OF category ON public.programs
  FOR EACH ROW EXECUTE FUNCTION public.enforce_formation_type_active();

-- ------------------------------------------------------------------ post-conditions
DO $$
BEGIN
  IF (SELECT count(*) FROM public.formation_types WHERE built_in) <> 9 THEN
    RAISE EXCEPTION 'expected 9 built-in formation types';
  END IF;
  IF EXISTS (SELECT 1 FROM public.programs p
              WHERE NOT EXISTS (SELECT 1 FROM public.formation_types t WHERE t.code = p.category)) THEN
    RAISE EXCEPTION 'a formation references an unknown type';
  END IF;
END $$;
