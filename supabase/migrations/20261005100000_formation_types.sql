-- ==================================================================
-- Formation types become institution-managed data (ADR-004 section 1).
--
-- A formation type is the PURPOSE / educational context of an offer (academic support, a language
-- course, school education, an extracurricular activity...). Until now it was a hard-coded CHECK
-- list on `programs.category`; institutions organise their offers differently, so the list moves
-- into a table the administration manages.
--
-- MODEL
--   formation_types(id, code UNIQUE, name, description, built_in, status, position)
--     code         stable identity, never changes. `programs.category` references it, so every
--                  existing formation keeps its value: no formation row is rewritten.
--     name         reference name. Built-in types are DISPLAYED through the dictionaries by code
--                  (fr/ar/en), like subjects and level systems; a custom type shows its name.
--     description  optional; built-in descriptions are translated by code too.
--     built_in     provided by Madrasti. Cannot be deleted, renamed or re-described (their labels
--                  are translated); an institution that uses other words creates its own type and
--                  deactivates the built-in one.
--     status       active / inactive. An inactive type stays valid on the formations that use it
--                  (readable, editable) but cannot be given to a new formation, or to a formation
--                  that changes type (t_programs_type_active).
--   A type used by a formation cannot be deleted (FK RESTRICT); an unused custom type can.
--
-- BUILT-IN TYPES (researched for Algerian private schools and educational/training centres)
--   formal_education       Enseignement scolaire: the regular schooling a private school provides,
--                          preparatory to secondary (national programme)
--   academic_support       Soutien scolaire
--   exam_preparation       Préparation aux examens (BEM, Bac, certifications)
--   language               Cours de langues (unchanged code; language schools hold their own
--                          approval, distinct from tutoring)
--   general_course         Formation générale: a structured course outside school support,
--                          languages and vocational training (programming, maths enrichment...)
--   extracurricular        Activités parascolaires: enrichment for pupils (mental arithmetic,
--                          chess, reading club, robotics club, arts, science activities)
--   professional_training  Formation professionnelle
--   workshop               Atelier: short or thematic sessions, usually without a progression
--   other                  Autre
--
-- SECURITY: read by every signed-in user (formation labels); written by administrators only (RLS).
-- Codes are generated by the database for new types; clients cannot create built-in types.
--
-- ROLLBACK
--   DROP TRIGGER IF EXISTS t_programs_type_active ON public.programs;
--   DROP FUNCTION IF EXISTS public.enforce_formation_type_active();
--   ALTER TABLE public.programs DROP CONSTRAINT IF EXISTS programs_category_fkey;
--   ALTER TABLE public.programs ADD CONSTRAINT programs_category_check CHECK (category IN
--     ('academic_support', 'language', 'exam_preparation', 'professional_training', 'workshop', 'other'));
--     (only once no formation uses another type)
--   DROP TABLE public.formation_types; DROP FUNCTION public.guard_formation_type();
-- ==================================================================

CREATE TABLE IF NOT EXISTS public.formation_types (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code        text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{1,59}$'),
  name        text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  description text CHECK (description IS NULL OR length(description) <= 500),
  built_in    boolean NOT NULL DEFAULT false,
  status      public.entity_status NOT NULL DEFAULT 'active',
  position    integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS formation_types_name_unique
  ON public.formation_types (lower(btrim(name)));

COMMENT ON TABLE public.formation_types IS
  'Formation types: the purpose / educational context of a formation. Built-in types are '
  'translated by code; institutions add their own. Referenced by programs.category (code).';

INSERT INTO public.formation_types (code, name, built_in, position) VALUES
