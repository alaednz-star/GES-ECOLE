/**
 * Formation types (20261005100000_formation_types.sql): the purpose / educational context of a
 * formation, managed by the institution. Rules live in `formation-type-model.ts` (pure, tested).
 *
 * SECURITY is RLS: every signed-in user reads the types (formation labels); only administrators
 * create, change or delete them. The database generates a new type's code, protects built-in
 * types (no delete, rename or new description) and refuses an inactive type on a new formation.
 *
 * Errors are thrown as the Supabase error object so callers can classify by `code` (23505 name
 * already used, 23503 type still used by formations, 23514 with the trigger's sentence).
 */

import { useCallback, useMemo } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useI18n } from "@/hooks/use-i18n";
import { programKeys } from "./programs";
import type { FormationTypeRow } from "./formation-type-model";

export const formationTypeKeys = {
  root: ["formation-types"] as const,
};

export function useFormationTypes() {
  return useQuery({
    queryKey: formationTypeKeys.root,
    queryFn: async (): Promise<FormationTypeRow[]> => {
      const { data, error } = await supabase
        .from("formation_types")
        .select("id, code, name, description, built_in, status, position")
        .order("position", { ascending: true })
        .order("name", { ascending: true });
      if (error) throw error;
      return (data ?? []).map((r) => ({
        id: r.id,
        code: r.code,
        name: r.name,
        description: r.description,
        builtIn: r.built_in,
        status: r.status as FormationTypeRow["status"],
        position: r.position,
      }));
    },
  });
}

/**
 * Display name and description of a formation type, in the interface language. A built-in type is
 * translated by its code (`programs.category.<code>`, `programs.typeDescription.<code>`); a custom
 * type shows the name and description the institution gave it. `labelOf(code)` also works for a
 * code whose row is not loaded yet.
 */
export function useFormationTypeLabels() {
  const { t } = useI18n();
  const { data: types = [] } = useFormationTypes();
  const byCode = useMemo(() => new Map(types.map((ft) => [ft.code, ft])), [types]);

  const label = useCallback(
    (ft: { code: string; builtIn: boolean; name: string }): string => {
      if (ft.builtIn) {
        const key = `programs.category.${ft.code}`;
        const translated = t(key);
        if (translated !== key) return translated;
      }
      return ft.name;
    },
    [t],
  );

  const description = useCallback(
    (ft: { code: string; builtIn: boolean; description: string | null }): string | null => {
      if (ft.builtIn) {
        const key = `programs.typeDescription.${ft.code}`;
        const translated = t(key);
        if (translated !== key) return translated;
      }
      return ft.description;
    },
    [t],
  );

  const labelOf = useCallback(
    (code: string): string => {
      const ft = byCode.get(code);
      if (ft) return label(ft);
      const key = `programs.category.${code}`;
      const translated = t(key);
      return translated !== key ? translated : code;
    },
    [byCode, label, t],
  );

  return { types, byCode, label, description, labelOf };
}

function invalidate(qc: ReturnType<typeof useQueryClient>) {
  void qc.invalidateQueries({ queryKey: formationTypeKeys.root });
  void qc.invalidateQueries({ queryKey: programKeys.root });
}

/** Creates a custom type (the database generates its code) or edits a custom type's text. */
export function useSaveFormationType() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: async (input: { id?: string; name: string; description: string | null }) => {
      if (input.id) {
        const { data, error } = await supabase
          .from("formation_types")
          .update({ name: input.name, description: input.description })
          .eq("id", input.id)
          .select("id");
        if (error) throw error;
        if (!data || data.length === 0) throw { code: "PGRST116", message: "Type not found" };
        return input.id;
      }
      const { data: last } = await supabase
        .from("formation_types")
        .select("position")
        .order("position", { ascending: false })
        .limit(1);
      const { data, error } = await supabase
        .from("formation_types")
        // `code` is generated by the database; this placeholder is replaced by the guard trigger.
        .insert({
          code: "custom_new",
          name: input.name,
          description: input.description,
          position: (last?.[0]?.position ?? 0) + 1,
        })
        .select("id");
      if (error) throw error;
      return data?.[0]?.id ?? null;
    },
    onSuccess: () => invalidate(qc),
  });
}

export function useSetFormationTypeStatus() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: async (input: { id: string; status: "active" | "inactive" }) => {
      const { data, error } = await supabase
        .from("formation_types")
        .update({ status: input.status })
        .eq("id", input.id)
        .select("id");
      if (error) throw error;
      if (!data || data.length === 0) throw { code: "PGRST116", message: "Type not found" };
    },
    onSuccess: () => invalidate(qc),
  });
}

/** Deletes an unused custom type. Built-in and used types are refused by the database. */
export function useDeleteFormationType() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: async (id: string) => {
      const { data, error } = await supabase
        .from("formation_types")
        .delete()
        .eq("id", id)
        .select("id");
      if (error) throw error;
      if (!data || data.length === 0) throw { code: "PGRST116", message: "Type not found" };
    },
    onSuccess: () => invalidate(qc),
  });
}
